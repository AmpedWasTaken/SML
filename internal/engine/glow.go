package engine

import (
	"errors"
	"fmt"
	"strconv"
	"strings"
)

// GlowOptions controls optional ANSI rendering for SML panel/table effects.
// Ordinary RenderWidth and RenderFrame remain plain, deterministic Unicode.
type GlowOptions struct {
	TrueColor bool
	// NoColor takes precedence over TrueColor for legacy terminal clients.
	NoColor bool
}

type glowInk struct {
	fg string
	bg string
}
type glowRGB struct {r,g,b int}

func glowParseHex(text string)(glowRGB,bool){
	if !validHexColor(text){return glowRGB{},false}
	value,err:=strconv.ParseUint(text[1:],16,24)
	if err!=nil{return glowRGB{},false}
	return glowRGB{int(value>>16),int(value>>8&255),int(value&255)},true
}
func glowShade(color glowRGB, level int)glowRGB{
	if level<0{level=0}
	if level>100{level=100}
	// Dim against the background rather than creating a wide bright panel.
	return glowRGB{(color.r*level+12*(100-level))/100,
		(color.g*level+15*(100-level))/100,
		(color.b*level+25*(100-level))/100}
}
func glowSGR(color glowRGB, background bool)string{
	kind:=38
	if background{kind=48}
	return fmt.Sprintf("\x1b[%d;2;%d;%d;%dm",kind,color.r,color.g,color.b)
}
func glowStroke(glyph string)bool{
	switch glyph {
	case "╭","╮","╰","╯","┌","┐","└","┘","╔","╗","╚","╝","┏","┓","┗","┛",
		"│","║","┃","─","═","━","┬","┴","┼","├","┤","┳","┻","╋","┣","┫",
		"┊","┋","+","|","-":return true
	}
	return false
}
func glowBounds(frame Frame,element Element)(int,int,int,int,bool){
	x0,y0:=element.Bounds.X,element.Bounds.Y
	x1,y1:=x0+element.Bounds.Width,y0+element.Bounds.Height
	if x0<0||y0<0||x1>frame.Width||y1>frame.Height||x0>=x1||y0>=y1{return 0,0,0,0,false}
	return x0,y0,x1,y1,true
}

// PaintGlowFrame returns styled ANSI SGR rows without changing glyphs, cell
// counts, layout, cursor state or hotspot positions. It does not move the
// cursor or clear rows. The host owns repaint scheduling and can disable RGB
// for an older PuTTY session. No new frames are generated by this function.
func PaintGlowFrame(frame Frame, opts GlowOptions)([]string,error){
	if err:=validateDiffFrame(frame);err!=nil{return nil,err}
	if opts.NoColor||!opts.TrueColor{return append([]string(nil),frame.Lines...),nil}
	inks:=make([][]glowInk,frame.Height)
	for y:=range inks{inks[y]=make([]glowInk,frame.Width)}
	styled:=false
	// Nested frame elements are recorded child-first. Paint parents first
	// so each nested table keeps its own accent instead of inheriting and
	// overwriting all its borders with the outer panel's glow color.
	for i:=len(frame.Elements)-1;i>=0;i-- {
		element:=frame.Elements[i]
		if element.Kind!="panel"&&element.Kind!="table"{continue}
		if element.Glow=="none"&&element.Accent==""&&element.HeaderStyle=="default"&&element.RowStyle=="plain"{continue}
		x0,y0,x1,y1,ok:=glowBounds(frame,element)
		if !ok{return nil,errors.New("invalid SML glow element bounds")}
		color,ok:=glowParseHex(element.GlowColor)
		if !ok{color,ok=glowParseHex(element.Accent)}
		if !ok{color=glowRGB{105,207,236}}
		brightness:=60
		switch element.Glow {
		case "soft":brightness=68
		case "medium":brightness=83
		case "strong":brightness=100
		}
		base:=glowSGR(glowShade(color,brightness),false)
		bright:=glowSGR(glowShade(color,min(100,brightness+18)),false)
		muted:=glowSGR(glowShade(color,40),false)
		headerY:=y0
		if element.Kind=="table" {
			switch frame.Cells[y0][x0].Grapheme {
			case "╭","┌","┏","╔":headerY=y0+1
			}
		}
		for y:=y0;y<y1;y++{
			for x:=x0;x<x1;x++{
				cell:=frame.Cells[y][x]
				if cell.Continuation{continue}
				glyph:=cell.Grapheme
				if !glowStroke(glyph){continue}
				// Emphasize corners and the top edge, but use dimmer vertical
				// dividers for less visual noise in dense plugin tables.
				ink:=base
				if y==y0||y==y1-1{ink=bright
				}else if x==x0||x==x1-1{ink=base
				}else{ink=muted}
				inks[y][x].fg=ink
				styled=true
			}
			if element.Kind!="table"||y!=headerY&&element.RowStyle!="striped" {continue}
			// Accent headers and subtle striped rows without coloring the
			// padded whitespace that caused earlier full-table blue blocks.
			isHeader:=y==headerY
			if !isHeader && (y-headerY)%2!=0 {continue}
			for x:=x0;x<x1;x++{
				cell:=frame.Cells[y][x]
				if cell.Continuation||cell.Grapheme==""||cell.Grapheme==" "||glowStroke(cell.Grapheme){continue}
				if isHeader {
					if element.HeaderStyle=="accent"||element.HeaderStyle=="solid" {
						inks[y][x].fg=bright
					}else if element.HeaderStyle=="muted" {inks[y][x].fg=muted}
					if element.HeaderStyle=="solid" {
						inks[y][x].bg=glowSGR(glowShade(color,14),true)
					}
				}else if element.RowStyle=="striped" {
					inks[y][x].bg=glowSGR(glowShade(color,8),true)
				}
				if inks[y][x].fg!=""||inks[y][x].bg!="" {styled=true}
			}
		}
	}
	if !styled{return append([]string(nil),frame.Lines...),nil}
	out:=make([]string,frame.Height)
	for y,row:=range frame.Cells {
		maxCell:=CellWidth(frame.Lines[y])
		if maxCell>frame.Width{maxCell=frame.Width}
		var b strings.Builder
		var old glowInk
		for x:=0;x<maxCell;x++{
			cell:=row[x]
			if cell.Continuation{continue}
			next:=inks[y][x]
			if next!=old{
				if old.fg!=""||old.bg!=""{b.WriteString("\x1b[0m")}
				if next.fg!=""{b.WriteString(next.fg)}
				if next.bg!=""{b.WriteString(next.bg)}
				old=next
			}
			if cell.Grapheme==""{b.WriteByte(' ')}else{b.WriteString(cell.Grapheme)}
		}
		if old.fg!=""||old.bg!=""{b.WriteString("\x1b[0m")}
		out[y]=b.String()
	}
	return out,nil
}
